# Access a range of tuple elements using slicing
items = (10, 20, 30, 40, 50, 60)
print("Original tuple:", items)
print("Elements from index 1 to 3:", items[1:4])
print("First three elements:", items[:3])
print("Last two elements:", items[-2:])
