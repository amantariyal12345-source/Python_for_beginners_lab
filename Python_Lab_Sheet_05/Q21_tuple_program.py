# Create a nested tuple and access inner elements
nested_tuple = ((1, 2, 3), ("A", "B", "C"), (10, 20, 30))
print("Nested tuple:", nested_tuple)
print("First element of second tuple:", nested_tuple[1][0])
print("Third element of first tuple:", nested_tuple[0][2])
